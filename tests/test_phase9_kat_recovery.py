    def test_m17_quick_recovery_fat32_ground_truth(self, tmp_path: Path):
        """M17: Verify parsing of active and deleted entries from synthetic FAT32 fixture."""
        raw_bytes, meta = SyntheticFixtureGenerator.generate_fat32_image(total_sectors=66000, seed=42)
        valid, diags = FixtureValidityGate.validate_fat32_fixture(raw_bytes, meta)
        assert valid, f"Fixture rejected by validity gate: {diags}"

        # Write fixture to disk
        img_path = tmp_path / "fat32_test.img"
        img_path.write_bytes(raw_bytes)

        # Parse root directory manually from known cluster offsets
        sector_size = 512
        reserved_sectors = 32
        sectors_per_fat = 64
        data_offset = (reserved_sectors + (2 * sectors_per_fat)) * sector_size
        cluster_size = 8 * sector_size

        # Root dir at cluster 2 (data offset 0)
        root_dir = raw_bytes[data_offset : data_offset + cluster_size]

        # Assert HELLO.TXT (Active)
        hello_entry = root_dir[32:64]
        assert hello_entry[0:11] == b"HELLO   TXT"
        hello_size = struct.unpack_from("<I", hello_entry, 28)[0]
        hello_cluster = struct.unpack_from("<H", hello_entry, 26)[0]
        assert hello_cluster == 3

        # Read cluster 3
        c3_off = data_offset + ((hello_cluster - 2) * cluster_size)
        recovered_hello = raw_bytes[c3_off : c3_off + hello_size]
        assert sha256_bytes(recovered_hello) == meta.expected_artifacts[0].expected_sha256

        # Assert DELET_NOTE.TXT (Deleted, 0xE5)
        del_entry = root_dir[64:96]
        assert del_entry[0] == 0xE5
        assert del_entry[1:11] == b"ELET_NOTE TXT"[:10]
        del_size = struct.unpack_from("<I", del_entry, 28)[0]
        del_cluster = struct.unpack_from("<H", del_entry, 26)[0]
        assert del_cluster == 4

        c4_off = data_offset + ((del_cluster - 2) * cluster_size)
        recovered_del = raw_bytes[c4_off : c4_off + del_size]
        assert sha256_bytes(recovered_del) == meta.expected_artifacts[1].expected_sha256

    def test_m17_quick_recovery_ntfs_ground_truth(self, tmp_path: Path):
        """M17: Verify parsing of resident and non-resident entries from synthetic NTFS fixture."""
        raw_bytes, meta = SyntheticFixtureGenerator.generate_ntfs_image(seed=42)
        valid, diags = FixtureValidityGate.validate_ntfs_fixture(raw_bytes, meta)
        assert valid, f"NTFS fixture rejected: {diags}"

        # Verify Record 16 (Resident active_case.txt)
        mft_offset = 4 * meta.cluster_size
        rec16 = raw_bytes[mft_offset + 16 * 1024 : mft_offset + 17 * 1024]
        assert rec16[0:4] == b"FILE"
        assert (rec16[22] & 0x01) == 0x01  # In-use flag

        # Extract resident data payload directly from expected artifact
        expected_active = next(a for a in meta.expected_artifacts if a.relative_path == "active_case.txt")
        assert expected_active.payload in rec16

        # Verify Record 17 (Deleted non-resident deleted_evidence.bin)
        rec17 = raw_bytes[mft_offset + 17 * 1024 : mft_offset + 18 * 1024]
        assert rec17[0:4] == b"FILE"
        assert (rec17[22] & 0x01) == 0x00  # Deleted flag (not in-use)

        expected_deleted = next(a for a in meta.expected_artifacts if a.relative_path == "deleted_evidence.bin")
        # Non-resident payload was placed at Cluster 10
        c10_off = 10 * meta.cluster_size
        recovered_stream = raw_bytes[c10_off : c10_off + expected_deleted.expected_size_bytes]
        assert sha256_bytes(recovered_stream) == expected_deleted.expected_sha256

    def test_m18_smart_recovery_signature_analysis(self):
        """M18: Smart Recovery detects valid format headers and rejects corrupted ones."""
        pdf_bytes = (
            b"%PDF-1.4\n"
            b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
            b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
            b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] >>\nendobj\n"
            b"xref\n0 4\n0000000000 65535 f \n0000000009 00000 n \n0000000058 00000 n \n0000000115 00000 n \n"
            b"trailer\n<< /Size 4 /Root 1 0 R >>\nstartxref\n190\n%%EOF\n"
        )
        res = PdfValidator.validate(pdf_bytes)
        assert res.is_valid is True
        assert res.state in (CandidateState.STRUCTURALLY_VALID, CandidateState.CONTENT_VALIDATED, CandidateState.RECOVERED_ARTIFACT)
        assert res.length == len(pdf_bytes)

        # Truncated / malformed header
        bad_pdf = b"%PDF-1.4\n" + b"A" * 100
        res_bad = PdfValidator.validate(bad_pdf)
        assert res_bad.is_valid is False
        assert res_bad.state in (CandidateState.CORRUPTED_INCOMPLETE, CandidateState.REJECTED, CandidateState.REJECTED_FALSE_POSITIVE, CandidateState.UNSUPPORTED)

