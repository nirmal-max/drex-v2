    def test_m23_raid5_degraded_xor_reconstruction_ground_truth(self):
        """M23: Reconstruct missing disk from 3-disk RAID 5 and assert bit-for-bit SHA-256 identity against ground truth."""
        ground_truth = SyntheticFixtureGenerator.generate_raid_groundtruth_set(
            raid_level="RAID_5",
            chunk_size=65536,
            disk_size_bytes=1048576,
            seed=42,
        )

        disk0 = bytearray(ground_truth.disk_images[0])
        # Disk 1 is MISSING/DEGRADED
        disk2 = bytearray(ground_truth.disk_images[2])

        # Execute XOR reconstruction for Disk 1
        num_stripes = len(disk0) // ground_truth.chunk_size
        reconstructed_disk1 = bytearray(len(disk0))

        chunk_size = ground_truth.chunk_size
        reconstructed_dataset = bytearray(len(ground_truth.original_dataset))

        for s in range(num_stripes):
            s_off = s * chunk_size
            e_off = (s + 1) * chunk_size
            c0 = disk0[s_off:e_off]
            c2 = disk2[s_off:e_off]
            # Disk 1 chunk is XOR of Disk 0 and Disk 2
            c1_reconstructed = bytes(a ^ b for a, b in zip(c0, c2))
            reconstructed_disk1[s_off:e_off] = c1_reconstructed

            # Determine layout to reassemble dataset
            p_disk = (3 - 1 - (s % 3))
            if p_disk == 2:
                # disk0=c0, disk1=c1, disk2=P
                reconstructed_dataset[s * 2 * chunk_size : (s * 2 + 1) * chunk_size] = c0
                reconstructed_dataset[(s * 2 + 1) * chunk_size : (s * 2 + 2) * chunk_size] = c1_reconstructed
            elif p_disk == 1:
                # disk0=c0, disk1=P, disk2=c1
                reconstructed_dataset[s * 2 * chunk_size : (s * 2 + 1) * chunk_size] = c0
                reconstructed_dataset[(s * 2 + 1) * chunk_size : (s * 2 + 2) * chunk_size] = c2
            else:
                # disk0=P, disk1=c0, disk2=c1
                reconstructed_dataset[s * 2 * chunk_size : (s * 2 + 1) * chunk_size] = c1_reconstructed
                reconstructed_dataset[(s * 2 + 1) * chunk_size : (s * 2 + 2) * chunk_size] = c2

        # 1. Assert reconstructed Disk 1 matches ground truth Disk 1
        assert sha256_bytes(reconstructed_disk1) == sha256_bytes(ground_truth.disk_images[1])

        # 2. Assert full reassembled dataset matches original pre-failure ground-truth SHA-256
        assert sha256_bytes(reconstructed_dataset) == ground_truth.original_dataset_sha256

    def test_m23_raid0_raid1_raid10_ground_truth(self):
        """M23: Reconstruct RAID 0, RAID 1, and RAID 10 sets against pre-failure ground truth."""
        # RAID 0: Interleaved reassembly
        gt0 = SyntheticFixtureGenerator.generate_raid_groundtruth_set(raid_level="RAID_0", chunk_size=65536, disk_size_bytes=262144, seed=42)
        d0, d1 = gt0.disk_images[0], gt0.disk_images[1]
        reassembled_r0 = bytearray(len(gt0.original_dataset))
        num_stripes = len(d0) // gt0.chunk_size
        for s in range(num_stripes):
            reassembled_r0[s * 2 * gt0.chunk_size : (s * 2 + 1) * gt0.chunk_size] = d0[s * gt0.chunk_size : (s + 1) * gt0.chunk_size]
            reassembled_r0[(s * 2 + 1) * gt0.chunk_size : (s * 2 + 2) * gt0.chunk_size] = d1[s * gt0.chunk_size : (s + 1) * gt0.chunk_size]
        assert sha256_bytes(reassembled_r0) == gt0.original_dataset_sha256

        # RAID 1: Mirror reconstruction
        gt1 = SyntheticFixtureGenerator.generate_raid_groundtruth_set(raid_level="RAID_1", disk_size_bytes=262144, seed=42)
        assert sha256_bytes(gt1.disk_images[0]) == gt1.original_dataset_sha256
        assert sha256_bytes(gt1.disk_images[1]) == gt1.original_dataset_sha256

        # RAID 10: Mirrored stripes reconstruction
        gt10 = SyntheticFixtureGenerator.generate_raid_groundtruth_set(raid_level="RAID_10", chunk_size=65536, disk_size_bytes=262144, seed=42)
        d0, d1, d2, d3 = gt10.disk_images
        # Disks 1 and 3 are missing/degraded -> recover from mirrors 0 and 2
        recovered_r10 = bytearray(len(gt10.original_dataset))
        num_stripes_10 = len(d0) // gt10.chunk_size
        for s in range(num_stripes_10):
            recovered_r10[s * 2 * gt10.chunk_size : (s * 2 + 1) * gt10.chunk_size] = d0[s * gt10.chunk_size : (s + 1) * gt10.chunk_size]
            recovered_r10[(s * 2 + 1) * gt10.chunk_size : (s * 2 + 2) * gt10.chunk_size] = d2[s * gt10.chunk_size : (s + 1) * gt10.chunk_size]
        assert sha256_bytes(recovered_r10) == gt10.original_dataset_sha256

