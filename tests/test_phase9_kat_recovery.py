    def test_m25_forensic_recovery_ledger_tamper_detection(self, tmp_path: Path):
        """M25: Forensic recovery ledger SHA-256 cryptographically hash-linked chaining and tamper sensitivity."""
        evidence_entries = [
            {
                "candidate_id": "cand_01",
                "recovered_filename": "file1.pdf",
                "size_bytes": 1024,
                "sha256": "A" * 64,
                "timestamp_utc": "2026-09-14T00:00:00Z",
                "verification_state": "HASH_MATCH",
            },
            {
                "candidate_id": "cand_02",
                "recovered_filename": "file2.jpg",
                "size_bytes": 2048,
                "sha256": "B" * 64,
                "timestamp_utc": "2026-09-14T00:01:00Z",
                "verification_state": "HASH_MATCH",
            },
        ]

        # Calculate chain hashes
        prev_hash = "0" * 64
        for entry in evidence_entries:
            chain_hash = ForensicRecoveryAdapter._compute_chain_hash(prev_hash, entry)
            entry["chain_hash"] = chain_hash
            prev_hash = chain_hash

        # Verify valid ledger
        ok, msg = ForensicRecoveryAdapter.verify_ledger(evidence_entries)
        assert ok is True
        assert msg == "OK"

        # Tamper with first entry size_bytes
        tampered_entries = [dict(e) for e in evidence_entries]
        tampered_entries[0]["size_bytes"] = 9999

        ok_tamper, msg_tamper = ForensicRecoveryAdapter.verify_ledger(tampered_entries)
        assert ok_tamper is False
        assert "TAMPER DETECTED" in msg_tamper
